"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";
import { cn } from "@/lib/utils";

const TABS = [
  { href: "/expenses", label: "Transacciones" },
  { href: "/expenses/analysis", label: "Análisis" },
];

/** Gastos' sections; the sidebar keeps Gastos active on every one. */
export function ExpensesTabs() {
  const pathname = usePathname();
  return (
    <nav aria-label="Secciones de Gastos" className="flex gap-1 border-b">
      {TABS.map((tab) => {
        const active = pathname === tab.href;
        return (
          <Link
            key={tab.href}
            href={tab.href}
            aria-current={active ? "page" : undefined}
            className={cn(
              "-mb-px border-b-2 px-3 py-2 text-sm font-medium transition-colors",
              active
                ? "border-primary text-foreground"
                : "border-transparent text-muted-foreground hover:text-foreground"
            )}
          >
            {tab.label}
          </Link>
        );
      })}
    </nav>
  );
}
